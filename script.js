// SHOPPING CART DATA
let cart = JSON.parse(localStorage.getItem("solevaCart")) || [];

// Memastikan produk lama memiliki jumlah minimal 1
cart = cart.map(function(product) {
    return {
        ...product,
        quantity: Number(product.quantity) || 1
    };
});

localStorage.setItem("solevaCart", JSON.stringify(cart));

// MENYIMPAN DATA KERANJANG
function saveCart() {
    localStorage.setItem("solevaCart", JSON.stringify(cart));
    renderCart();
}

// MENAMPILKAN PRODUK DI KERANJANG
function renderCart() {
    const cartItems = document.getElementById("cartItems");
    const cartCount = document.getElementById("cartCount");
    const cartTotalItems = document.getElementById("cartTotalItems");

    if (!cartItems) return;

    const totalQuantity = cart.reduce(function(total, product) {
    return total + (Number(product.quantity) || 1);
}, 0);

    cartCount.textContent = totalQuantity;
    cartTotalItems.textContent = totalQuantity;

    if (cart.length === 0) {
        cartItems.innerHTML = `
            <p class="cart-empty">
                Your cart is currently empty.
            </p>
        `;
        return;
    }

    cartItems.innerHTML = "";

    cart.forEach(function(product, index) {
        const item = document.createElement("div");

        item.className = "cart-item";

        item.innerHTML = `
            <img src="${product.image}" alt="${product.name}">

            <div class="cart-item-info">
                <h4>${product.name}</h4>
                <p>${product.price || "Lihat harga di Shopee"}</p>

                <div class="quantity-control">
                    <button type="button"
                        class="quantity-minus"
                        data-index="${index}">−</button>

                    <span>${Number(product.quantity) || 1}</span>

                    <button type="button"
                        class="quantity-plus"
                        data-index="${index}">+</button>
                </div>

                <a href="${product.link}"
                   class="shop-now-button"
                   target="_blank"
                   rel="noopener noreferrer">
                    SHOP NOW
                </a>
            </div>
        `;

        cartItems.appendChild(item);
    });
}

// MENAMBAHKAN PRODUK KE KERANJANG
document.addEventListener("DOMContentLoaded", function() {

    const addButton = document.getElementById("collectionAddToCart");
    const cartItems = document.getElementById("cartItems");

    if (addButton) {
        addButton.addEventListener("click", function() {

            const productName = this.dataset.name;
            const productLink = this.dataset.link;

            const existingProduct = cart.find(function(product) {
                return product.name === productName &&
                       product.link === productLink;
            });

            if (existingProduct) {
                existingProduct.quantity += 1;
            } else {
                cart.push({
                    name: productName,
                    image: this.dataset.image,
                    price: this.dataset.price,
                    link: productLink,
                    quantity: 1

                    
                });
            }

            saveCart();

            alert("Product added to cart!");
        });
    }
    // ADD TO CART RECOMMENDED PRODUCTS
const productContainer = document.getElementById("detailProductContainer");

if (productContainer) {
    productContainer.addEventListener("click", function(event) {
        const button = event.target.closest(".detail-add-to-cart");

        if (!button) return;

        const productName = button.dataset.name;
        const productLink = button.dataset.link;

        const existingProduct = cart.find(function(product) {
            return product.name === productName &&
                   product.link === productLink;
        });

        if (existingProduct) {
            existingProduct.quantity += 1;
        } else {
            cart.push({
                name: productName,
                image: button.dataset.image,
                price: button.dataset.price,
                link: productLink,
                quantity: 1
            });
        }

        saveCart();

        alert("Product added to cart!");
    });


    // ABOUT SOLÉVA POP-UP
    const learnMoreButton = document.getElementById("learnMoreButton");
    const aboutModal = document.getElementById("aboutModal");
    const closeAboutModal = document.getElementById("closeAboutModal");

    if (learnMoreButton && aboutModal && closeAboutModal) {

        learnMoreButton.addEventListener("click", function() {
            aboutModal.style.display = "flex";
        });

        closeAboutModal.addEventListener("click", function() {
            aboutModal.style.display = "none";
        });

        aboutModal.addEventListener("click", function(event) {
            if (event.target === aboutModal) {
                aboutModal.style.display = "none";
            }
        });

    }

}

    // TOMBOL TAMBAH DAN KURANGI JUMLAH PRODUK
if (cartItems) {
    cartItems.addEventListener("click", function(event) {

        const button = event.target.closest(
            ".quantity-plus, .quantity-minus"
        );

        if (!button) return;

        const index = Number(button.dataset.index);

        if (!cart[index]) return;

        if (button.classList.contains("quantity-plus")) {
            cart[index].quantity = (Number(cart[index].quantity) || 1) + 1;
        }

        if (button.classList.contains("quantity-minus")) {
            cart[index].quantity = (Number(cart[index].quantity) || 1) - 1;

            if (cart[index].quantity <= 0) {
                cart.splice(index, 1);
            }
        }

        saveCart();
    });
}

renderCart();
});
    